let firstName = "karan"; 

console.log(firstName.length); // Output: 5
console.log(firstName.toUpperCase()); // Output: "KARAN"
console.log(firstName.toLowerCase()); // Output: "karan"
console.log(firstName.charAt(0)); // Output: "k"
console.log(firstName.charAt(3)); // Output: "a"
console.log(firstName.indexOf("a")); // Output: 1
console.log(firstName.slice(1, 4)); // Output: "ara"
console.log(firstName.replace("karan", "John")); // Output: "John"    
console.log(firstName.split("")); // Output: ["k", "a", "r", "a", "n"]
